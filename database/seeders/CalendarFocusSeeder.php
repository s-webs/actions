            ['2026-11-01', 'Подготовка к независимой оценке 3 курса, оценочные инструменты, КИС/OSCE, ПМСП-практика', 'МС, РГ'],
            ['2026-12-01', 'Полугодовой отчёт, сессия, LMS-контент и данные, академическая честность, анкетирование, самооценка', 'МС, ректорат'],
            ['2027-01-01', 'Итоги зимней сессии, данные ИС, группы риска, logbook/EPA, корректирующие меры', 'РГ, МС'],
            ['2027-02-01', 'Иностранный/англоязычный контингент, оценочные риски, качество ОП, студенческие сервисы', 'РГ, МС'],
            ['2027-03-01', 'ВОП/интернатура, клинические навыки, OSCE, работодатели, профильная подготовка', 'МС, РГ'],
            ['2027-04-01', 'Независимые экзамены, итоговая аттестация, библиотечные и цифровые ресурсы, олимпиады', 'МС, РГ'],
