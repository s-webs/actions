        ];

        foreach ($months as [$month, $focusText, $reviewBody]) {
            // updateOrCreate(['month' => ...]) не находит совпадение: `month` хранится
            // как полная дата-время (каст `date` не влияет на формат сохранения), а
            // updateOrCreate сравнивает значение как есть, без приведения через whereDate.
            CalendarFocus::query()
                ->whereDate('month', $month)
                ->first()
                ?->update(['focus_text' => $focusText, 'review_body' => $reviewBody])
                ?? CalendarFocus::create([
                    'month' => $month,
                    'focus_text' => $focusText,
                    'review_body' => $reviewBody,
                ]);
        }
    }
}
