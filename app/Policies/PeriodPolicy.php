<?php

namespace App\Policies;

use App\Models\User;

/**
 * Закрытие периода — единственное действие в [[Роли и права#Матрица]], где у
 * проректора явно стоит «—», а не ✅, в отличие от большинства других строк («может
 * выполнить любое действие координатора»). Матрица здесь конкретнее общего правила —
 * закрытие периода оставлено координатору намеренно.
 */
class PeriodPolicy
{
    public function close(User $user): bool
    {
        return $user->hasRole('coordinator');
    }
}
